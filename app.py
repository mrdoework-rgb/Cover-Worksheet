DEFAULT_WORKSHEET_STRUCTURE = """Every worksheet must structurally contain the following content:
  1. Core Text: A short paragraph or bulleted list explaining the absolute core facts/concepts. Use essential keywords as technical vocabulary. If a core formula or relationship exists, include it.
  2. Quick Questions: Exactly 4 questions that elicit a keyword defined in the core text, followed by exactly 4 binary-choice questions formatted as "Does [Factor A] affect [Option X] or [Option Y]?"
  3. True or False: Exactly 8 simple statement verification questions.
  4. Factor Summary Table: A comparison table with 2 to 5 columns where students classify 4 distinct items/factors from the text. Leave about 60% of cells empty for students to complete.
  5. Fill in the Blanks: A short paragraph cloze activity (3-4 sentences) with a clean Word Bank directly under it.
  6. Application Problems: Exactly 6 simple contextual questions that ask students to apply the content.
  7. Extension: Exactly 3 higher-tier contextual application questions using novel scenarios, evaluating safety/experimental designs, or explaining why.
"""

KEYWORD_INSTRUCTION = "Underline or Highlight these Keywords:-"
ALLOWED_BLOCK_TYPES = {"subheading", "paragraph", "question", "long_question", "answer_key", "image", "table"}
PROMPT_TEMPLATE = """You are an expert GCSE Science worksheet creator specializing in clear resources for lower-attaining and SEND students.

Create a minimalist, highly structured cover lesson worksheet for the requested topic. Output one raw JSON object only, with no Markdown fences or conversational text.

TARGET TOPIC
Topic: {topic}
Year Group: {year_group}
Ability of the group: {ability}
Requested core paragraph length: approximately {core_text_word_count} words. This is soft guidance: aim for 75% to 125% of the requested count ({core_text_min_words}-{core_text_max_words} words). Prioritize scientific accuracy and clear age-appropriate writing if a small deviation is necessary.

PEDAGOGICAL CONSTRAINTS
- Keep text minimal, clear, age-appropriate, and easy to scan.
- Place the core explanation ONLY in the top-level `core_text` field. It must be one short paragraph or bulleted string. Do not copy it into `document_blocks`.
- Aim for the requested core paragraph word count above, allowing the stated 25% range.
- The `core_text` must be completely unbolded plain text. Do not include ** markers or other bold formatting in it. The application will render all core text in regular, non-bold type.
- Return the core keywords ONLY in the top-level `core_keywords` field as a JSON array of 1 to 8 distinct strings taken from `core_text`. Do not include a keyword instruction or keyword list in `document_blocks`.
- The application renders the core text in the bordered box and adds the instruction "Underline or Highlight these Keywords:-" and the formatted keyword list immediately below the box. Do not output that instruction yourself.
- Do not use bold markers in `core_keywords`; each array item must be the plain keyword or phrase. Use **bold markers** only in other content when needed.
- For Application Problems and Extension, use `long_question` blocks.
- The final `document_blocks` item must be an `answer_key` block containing a numbered list of answers.
{worksheet_structure}

STRICT JSON SCHEMA — FOLLOW EXACTLY
The top-level JSON object must contain exactly these four keys, each exactly once:
- `worksheet_title`: a string.
- `core_text`: a string containing only the unbolded core explanation.
- `core_keywords`: an array of 1 to 8 distinct plain-text keyword strings. No Markdown asterisks and no instruction text.
- `document_blocks`: an array containing all worksheet content EXCEPT the core explanation, keyword instruction, and keyword list.

Each `document_blocks` item must have exactly one allowed `type` value: `subheading`, `paragraph`, `question`, `long_question`, `answer_key`, `image`, or `table`. For text-based types and `image`, include `content` as a string. For `table`, include `table_data` with `has_headers` (boolean), `column_count` (integer), and `rows` (array of arrays of strings); do not include `content` for a table.

Do not add any other top-level keys. Do not duplicate any top-level key. Do not put core text, core keywords, the keyword instruction, or a keyword list in `document_blocks`. The exact instruction and keyword list are generated by the application, not by you.

FORMATTING
- Wrap bold text in `**double asterisks**` in normal worksheet text, but NEVER in `core_text` or `core_keywords`.
- Format chemical formulas and numerical subscripts with HTML `<sub>` tags, e.g. H<sub>2</sub>O, CO<sub>2</sub>, Ca(NO<sub>3</sub>)<sub>2</sub>.
- Write states of matter as ordinary text in parentheses, e.g. 2H<sub>2</sub>O(l).
- For True or False, make each statement a `question` block ending in ` [True / False]`.
- For Fill in the Blanks, use a `paragraph` block with blanks as `______`, followed by a `paragraph` block containing the Word Bank.

Return the complete raw JSON object for the topic. No additional text."""


def build_gemini_response_schema():
    return {
        "type": "object",
        "properties": {
            "worksheet_title": {"type": "string"},
            "core_text": {"type": "string"},
            "core_keywords": {"type": "array", "items": {"type": "string"}, "minItems": 1, "maxItems": 8},
            "document_blocks": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "type": {"type": "string", "enum": sorted(ALLOWED_BLOCK_TYPES)},
                        "content": {"type": "string"},
                        "table_data": {
                            "type": "object",
                            "properties": {
                                "has_headers": {"type": "boolean"},
                                "column_count": {"type": "integer"},
                                "rows": {"type": "array", "items": {"type": "array", "items": {"type": "string"}}},
                            },
                            "required": ["has_headers", "column_count", "rows"],
                        },
                    },
                    "required": ["type"],
                },
            },
        },
        "required": ["worksheet_title", "core_text", "core_keywords", "document_blocks"],
    }


def append_science_text(paragraph, raw_text):
    """Render Markdown bold markers and chemical subscript tags as Word formatting."""
    if raw_text is None:
        return
    text = str(raw_text)
    pattern = re.compile(r'(\*\*.+?\*\*|<sub>.+?</sub>)')
    last_end = 0
    for match in pattern.finditer(text):
        if match.start() > last_end:
            paragraph.add_run(text[last_end:match.start()])
        token = match.group(1)
        if token.startswith("**"):
            run = paragraph.add_run(token[2:-2])
            run.font.bold = True
        else:
            run = paragraph.add_run(token[5:-6])
            run.font.subscript = True
        last_end = match.end()
    if last_end < len(text):
        paragraph.add_run(text[last_end:])


def append_core_text(paragraph, raw_text):
    """Render core text without bold, even if Gemini accidentally returns ** markers."""
    plain_text = re.sub(r"\*\*(.*?)\*\*", r"\1", str(raw_text or ""))
    append_science_text(paragraph, plain_text)


def clean_question_text(raw_text):
    if not raw_text:
        return ""
    return re.sub(r'^\s*(?:\d+[.)]\s*|[A-Za-z][.)]\s*)+', '', str(raw_text)).strip()


def render_section_label(text):
    st.markdown(f"<strong>{text}</strong>", unsafe_allow_html=True)


def set_cell_border(cell, size_pt=2.25, color="000000"):
    ns = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        edge = OxmlElement(f"w:{side}")
        edge.set(f"{ns}val", "single")
        edge.set(f"{ns}sz", str(int(size_pt * 8)))
        edge.set(f"{ns}space", "0")
        edge.set(f"{ns}color", color)
        borders.append(edge)
    tc_pr.append(borders)


def build_gemini_prompt(topic, year_group=None, ability=None, worksheet_structure=None, core_text_word_count=150):
    requested_words = int(core_text_word_count)
    return PROMPT_TEMPLATE.format(
        topic=topic.strip(),
        year_group=(year_group or "unknown").strip(),
        ability=(ability or "unknown").strip(),
        core_text_word_count=requested_words,
        core_text_min_words=round(requested_words * 0.75),
        core_text_max_words=round(requested_words * 1.25),
        worksheet_structure=(worksheet_structure or DEFAULT_WORKSHEET_STRUCTURE).strip(),
    )


def get_gemini_api_key():
    api_key = os.getenv("GEMINI_API_KEY")
    if api_key:
        return api_key
    try:
        return st.secrets["GEMINI_API_KEY"]
    except Exception:
        return None


def resolve_gemini_api_key():
    st.markdown("Watch this video to learn how to get a free Gemini API key")
    components.iframe("https://www.youtube.com/embed/Uyn-P2nRvDA", height=158, width=280, scrolling=False)
    st.markdown("Create your Google Gemini API key at [https://aistudio.google.com/](https://aistudio.google.com/).")
    return st.text_input("Gemini API key", type="password", placeholder="Enter your Gemini API key", help="This value is used for the request when provided.")


def clean_json_text(raw_text):
    text = raw_text.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        text = "\n".join(lines[1:-1]) if len(lines) >= 2 else text.strip("`")
    return text.strip()


def reject_duplicate_json_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Gemini JSON contains a duplicate key: {key}")
        result[key] = value
    return result


def validate_worksheet_json(data):
    expected_keys = {"worksheet_title", "core_text", "core_keywords", "document_blocks"}
    if not isinstance(data, dict) or set(data) != expected_keys:
        raise ValueError("Gemini JSON must contain exactly worksheet_title, core_text, core_keywords, and document_blocks.")
    if not isinstance(data["worksheet_title"], str) or not data["worksheet_title"].strip():
        raise ValueError("Gemini JSON worksheet_title must be a non-empty string.")
    if not isinstance(data["core_text"], str) or not data["core_text"].strip():
        raise ValueError("Gemini JSON core_text must be a non-empty string.")
    keywords = data["core_keywords"]
    if not isinstance(keywords, list) or not 1 <= len(keywords) <= 8:
        raise ValueError("Gemini JSON core_keywords must be an array containing 1 to 8 keywords.")
    if any(not isinstance(word, str) or not word.strip() or "**" in word for word in keywords):
        raise ValueError("Every core_keywords item must be a non-empty plain-text string without bold markers.")
    if len({word.strip().casefold() for word in keywords}) != len(keywords):
        raise ValueError("Gemini JSON core_keywords must not contain duplicate keywords.")
    if not isinstance(data["document_blocks"], list):
        raise ValueError("Gemini JSON document_blocks must be an array.")
    for index, block in enumerate(data["document_blocks"]):
        if not isinstance(block, dict) or block.get("type") not in ALLOWED_BLOCK_TYPES:
            raise ValueError(f"Gemini JSON document_blocks item {index + 1} has an invalid type.")
        if block["type"] == "paragraph":
            content = str(block.get("content", "")).strip()
            if content == KEYWORD_INSTRUCTION or re.fullmatch(r'(?:\*\*[^*]+\*\*(?:\s*,\s*)?)+', content):
                raise ValueError("Gemini JSON must not put the keyword instruction/list in document_blocks.")
    return data


def parse_gemini_response(response_data):
    try:
        text = response_data["candidates"][0]["content"]["parts"][0]["text"]
    except (KeyError, IndexError, TypeError) as exc:
        raise ValueError("Gemini response did not contain a usable content block.") from exc
    parsed = json.loads(clean_json_text(text), object_pairs_hook=reject_duplicate_json_keys)
    return validate_worksheet_json(parsed)


def call_gemini_api(topic, year_group=None, ability=None, api_key=None, worksheet_structure=None, core_text_word_count=150):
    if not topic or not topic.strip():
        raise ValueError("Please enter a topic first.")
    resolved_key = api_key or get_gemini_api_key()
    if not resolved_key:
        raise ValueError("Enter a Gemini API key or set the GEMINI_API_KEY environment variable or Streamlit secret before generating a worksheet.")
    model = os.getenv("GEMINI_MODEL") or "gemini-2.5-flash"
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={resolved_key}"
    payload = {
        "contents": [{"role": "user", "parts": [{"text": build_gemini_prompt(topic, year_group, ability, worksheet_structure, core_text_word_count)}]}],
        "generationConfig": {"temperature": 0.1, "response_mime_type": "application/json", "response_schema": build_gemini_response_schema()},
    }
    request = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            response_data = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="ignore")
        raise RuntimeError(f"Gemini API request failed ({exc.code}): {detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Unable to reach Gemini API: {exc}") from exc
    return parse_gemini_response(response_data)


def is_answer_key_heading(content):
    return re.sub(r'\s+', ' ', str(content or "")).strip().lower() == "answer key"


def iter_all_paragraphs(doc):
    seen = set()
    for paragraph in doc.paragraphs:
        seen.add(id(paragraph))
        yield paragraph
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    if id(paragraph) not in seen:
                        seen.add(id(paragraph))
                        yield paragraph


def normalize_placeholder_text(value):
    return (value or "").replace("\u00a0", " ").strip()


def insert_paragraph_after(doc, element, style="Normal"):
    paragraph = doc.add_paragraph(style=style)
    paragraph._p.getparent().remove(paragraph._p)
    element.addnext(paragraph._p)
    return paragraph


def insert_keywords_after_core_box(doc, placeholder_paragraph, keywords):
    ancestor = placeholder_paragraph._p.getparent()
    table_element = None
    while ancestor is not None:
        if ancestor.tag == qn("w:tbl"):
            table_element = ancestor
            break
        ancestor = ancestor.getparent()
    anchor = table_element if table_element is not None else placeholder_paragraph._p
    instruction = insert_paragraph_after(doc, anchor)
    append_science_text(instruction, KEYWORD_INSTRUCTION)
    keyword_line = insert_paragraph_after(doc, instruction._p)
    append_science_text(keyword_line, ", ".join(f"**{word.strip()}**" for word in keywords))


def generate_worksheet(json_data, template_path):
    template = Path(template_path)
    doc = Document(template) if template.exists() else Document()
    title = json_data["worksheet_title"]
    core_text = json_data["core_text"]
    core_keywords = json_data["core_keywords"]
    blocks = json_data["document_blocks"]
    core_box_rendered = False
    for paragraph in list(iter_all_paragraphs(doc)):
        text = normalize_placeholder_text(paragraph.text)
        if "[[WORKSHEET_TITLE]]" in text:
            paragraph.text = ""
            append_science_text(paragraph, title)
        elif "[[CORE_TEXT_BOX]]" in text and not core_box_rendered:
            paragraph.text = ""
            # Never render markdown bold from core_text; HTML chemical subscripts remain supported.
            append_core_text(paragraph, core_text)
            insert_keywords_after_core_box(doc, paragraph, core_keywords)
            core_box_rendered = True
        elif "[[CONTENT_HERE]]" in text:
            for block in blocks:
                block_type = block["type"]
                if block_type == "subheading":
                    content = block.get("content", "")
                    if is_answer_key_heading(content):
                        continue
                    new_p = paragraph.insert_paragraph_before("")
                    new_p.style = "Heading 2"
                    append_science_text(new_p, content)
                elif block_type == "paragraph":
                    new_p = paragraph.insert_paragraph_before("")
                    new_p.style = "Normal"
                    append_science_text(new_p, block.get("content", ""))
                elif block_type in ("question", "long_question"):
                    new_p = paragraph.insert_paragraph_before("")
                    new_p.style = "List Number"
                    if block_type == "long_question":
                        new_p.paragraph_format.space_after = Pt(12)
                    append_science_text(new_p, clean_question_text(block.get("content", "")))
                    if block_type == "long_question":
                        for _ in range(2):
                            blank_p = paragraph.insert_paragraph_before("")
                            blank_p.style = "Normal"
                            blank_p.paragraph_format.space_before = Pt(0)
                            blank_p.paragraph_format.space_after = Pt(0)
                elif block_type == "image":
                    new_p = paragraph.insert_paragraph_before("")
                    new_p.style = "Normal"
                    run = new_p.add_run(f"[ 📷 PLACEHOLDER: {block.get('content', 'Insert image here')} ]")
                    run.font.bold = True
                elif block_type == "table":
                    table_data = block.get("table_data", {})
                    rows = table_data.get("rows", [])
                    if rows:
                        column_count = table_data.get("column_count", len(rows[0]))
                        table = doc.add_table(rows=len(rows), cols=column_count)
                        try:
                            table.style = "Science_Table_Style"
                        except KeyError:
                            pass
                        paragraph._p.addprevious(table._tbl)
                        for row_index, row_data in enumerate(rows):
                            for column_index, cell_text in enumerate(row_data[:column_count]):
                                cell = table.cell(row_index, column_index)
                                cell_paragraph = cell.paragraphs[0]
                                cell_paragraph.text = ""
                                append_science_text(cell_paragraph, str(cell_text))
                                set_cell_border(cell)
            paragraph._element.getparent().remove(paragraph._element)
    if not core_box_rendered:
        st.warning("The Word template does not contain a [[CORE_TEXT_BOX]] placeholder; core text and keywords were not inserted.")
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer, title


def generate_answer_key_document(json_data, template_path):
    template = Path(template_path)
    doc = Document(template) if template.exists() else Document()
    title = json_data["worksheet_title"]
    answer_blocks = [block for block in json_data["document_blocks"] if block["type"] == "answer_key"]
    for paragraph in list(iter_all_paragraphs(doc)):
        text = normalize_placeholder_text(paragraph.text)
        if "[[WORKSHEET_TITLE]]" in text:
            paragraph.text = ""
            append_science_text(paragraph, f"{title} - Answers")
        elif "[[CONTENT_HERE]]" in text:
            for block in answer_blocks:
                new_p = paragraph.insert_paragraph_before("")
                new_p.style = "Normal"
                append_science_text(new_p, block.get("content", ""))
            paragraph._element.getparent().remove(paragraph._element)
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer, f"{title} - Answers"


def prepare_template_path(uploaded_template):
    default_template = Path("Generic Template.docx")
    if uploaded_template is None:
        if default_template.exists():
            return str(default_template)
        raise FileNotFoundError("The default template file 'Generic Template.docx' was not found.")
    temp_dir = Path(tempfile.gettempdir()) / "cover_worksheet_templates"
    temp_dir.mkdir(exist_ok=True)
    safe_name = Path(uploaded_template.name).stem.replace(" ", "_")
    temp_path = temp_dir / f"{safe_name}_{uuid4().hex}.docx"
    temp_path.write_bytes(uploaded_template.getvalue())
    return str(temp_path)


def main():
    st.set_page_config(page_title="Science Worksheet Generator", page_icon="🔬")
    st.title("Worksheet Generator")
    st.write("This app helps you create a ready-to-use worksheet in a few steps. Enter the topic, year group, and ability level; Gemini creates the content, and the app turns it into a downloadable Word document.")
    render_section_label("What should this worksheet be about")
    topic_input = st.text_input("", placeholder="e.g. Photosynthesis: equation and factors affecting rate", label_visibility="collapsed")
    render_section_label("Year Group")
    year_group_input = st.text_input("", placeholder="e.g. Year 10", label_visibility="collapsed")
    render_section_label("What is the ability of the group?")
    ability_input = st.text_input("", placeholder="e.g. Lower-attaining / mixed / high ability", label_visibility="collapsed")
    worksheet_structure_input = st.text_area("Worksheet elements-You can modify the prompt here", value=DEFAULT_WORKSHEET_STRUCTURE, height=220, help="Edit the worksheet structure here before generating the worksheet.")
    core_text_word_count = st.slider("Main paragraph target length (words)", min_value=50, max_value=500, value=150, step=10, help="Soft guidance for Gemini. The paragraph should be within 25% of this target where practical.")
    api_key_input = resolve_gemini_api_key()
    uploaded_template = st.file_uploader("Optional: upload a Word template (.docx)", type=["docx"])
    show_gemini_json = st.checkbox("Show Gemini JSON response (debug)", value=False, help="When enabled, displays the parsed JSON returned by Gemini after generating a worksheet.")
    for key, default in (("worksheet_bytes", None), ("worksheet_file_name", "worksheet.docx"), ("answer_bytes", None), ("answer_file_name", "answers.docx")):
        if key not in st.session_state:
            st.session_state[key] = default
    with st.expander("Template guidance", expanded=False):
        st.write("The template is a Word document containing the structure and formatting for the worksheet. Use [[WORKSHEET_TITLE]], [[CORE_TEXT_BOX]], and [[CONTENT_HERE]] placeholders where the generated content should appear.")
        st.table({"Style": ["Heading 2", "Normal", "List Number"], "Used for": ["Section headings", "Paragraph text and instructions", "Numbered questions"]})
        template_path = Path("Generic Template.docx")
        if template_path.exists():
            st.download_button("Download starter template", data=template_path.read_bytes(), file_name="Generic Template.docx", mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document")
    with st.expander("Environmental Impact", expanded=False):
        st.write("Each use of this app consumes around 1000 input tokens and 5000 output tokens. Actual energy use varies by model and request.")
    if st.button("Generate Worksheet", type="primary"):
        if topic_input.strip():
            try:
                with st.spinner("Contacting Gemini to build the worksheet..."):
                    json_data = call_gemini_api(topic_input, year_group=year_group_input, ability=ability_input, api_key=api_key_input or None, worksheet_structure=worksheet_structure_input, core_text_word_count=core_text_word_count)
                if show_gemini_json:
                    st.subheader("Gemini JSON response")
                    st.json(json_data)
                template_path = prepare_template_path(uploaded_template)
                word_buffer, doc_title = generate_worksheet(json_data, template_path)
                answer_buffer, answer_title = generate_answer_key_document(json_data, template_path)
                st.session_state["worksheet_bytes"] = word_buffer.getvalue()
                st.session_state["worksheet_file_name"] = f"{doc_title}.docx"
                st.session_state["answer_bytes"] = answer_buffer.getvalue()
                st.session_state["answer_file_name"] = f"{answer_title}.docx"
                st.success("Worksheet generated successfully!")
            except Exception as exc:
                st.error(f"❌ An error occurred: {exc}")
        else:
            st.error("Please enter a topic first.")
    if st.session_state.get("worksheet_bytes") is not None:
        st.download_button("📥 Download Word Document", data=st.session_state["worksheet_bytes"], file_name=st.session_state["worksheet_file_name"], mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document")
    if st.session_state.get("answer_bytes") is not None:
        st.download_button("📥 Download Answers Document", data=st.session_state["answer_bytes"], file_name=st.session_state["answer_file_name"], mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document")


if __name__ == "__main__":
    main()
